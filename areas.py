# エリア名 → エリアコードの逆引きマップ
AREA_NAME_MAP: dict[str, str] = {v: k for k, v in AREA_CODE_MAP.items()}


def search_area_by_name(name: str) -> list[dict[str, str]]:
    """
    エリア名の部分一致でエリアコードを検索する

    予報区名のほか、管轄の気象台名（例: 函館・旭川・帯広）でも検索できる。
    「北海道」のように地方名だけを指定した場合は、その地方の予報区をすべて返す。

    Args:
        name: 検索キーワード（例: "沖縄", "東京", "函館"）

    Returns:
        マッチしたエリアのリスト [{"code": "...", "name": "..."}]
    """
    results = []
    for code, area_name in AREA_CODE_MAP.items():
        office = AREA_OFFICE_MAP.get(code, "")
        if name in area_name or name in office or (name == "北海道" and code.startswith("01")):
            results.append({"code": code, "name": area_name})
    return results
